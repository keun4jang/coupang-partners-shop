/** 제목을 [진하게?, 글자] 조각으로 - 키워드가 없으면 전체 보통 */
export function keywordSpans(title: string): { t: string; strong: boolean }[] {
  const kws = (STEP_KEYWORDS[title] ?? []).filter(Boolean);
  if (!kws.length) return [{ t: title, strong: false }];
  const marks = new Array(title.length).fill(false);
  for (const k of kws) {
    let i = title.indexOf(k);
    while (i >= 0) {
      for (let j = i; j < i + k.length; j++) marks[j] = true;
      i = title.indexOf(k, i + k.length);
    }
  }
  const out: { t: string; strong: boolean }[] = [];
  for (let i = 0; i < title.length; i++) {
    const last = out[out.length - 1];
    if (last && last.strong === marks[i]) last.t += title[i];
    else out.push({ t: title[i], strong: marks[i] });
  }
  return out;
}
