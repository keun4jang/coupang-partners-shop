/**
 * "혹하는 정도" 점수 (숏폼 스크롤을 멈추게 하는 힘).
 *
 * 방향(사장님 지침): 가격은 기준이 아니다. 비싸도 상관없고, 필요한 사람은 어차피 산다.
 * 중요한 건 "저게 뭐야?" 하고 눌러보게 만드는 아이템인지다.
 *
 * 쿠팡 검색 API 는 평점·리뷰수를 주지 않으므로(productId/이름/가격/이미지/로켓 여부가 전부)
 * 판단 근거는 사실상 "상품명" 하나다. 그래서 숏폼에서 실제로 잘 먹히는 성질을
 * 키워드 그룹으로 점수화한다.
 *
 * 핵심 기준은 "영상으로 보여줄 게 있는가":
 *  - 움직임·변신이 보이면 15초 안에 시청자를 붙잡는다 (접히고, 늘어나고, 돌아가고)
 *  - 정체가 바로 안 읽히면 훅 패턴 ①(지칭 은폐)·②(상식 반전)이 강하게 걸린다
 *  - 반대로 소모품·리필처럼 화면에서 변화가 없는 건 아무리 잘 팔려도 훅이 안 나온다
 */

/** 점수 그룹: [정규식, 가중치, 설명] */
const APPEAL_RULES: Array<[RegExp, number, string]> = [
  // 정체 불명 + 신기함 - 훅 ①②가 바로 나온다
  [/신박|신기|아이디어\s*상품|기발|희한|별걸\s*다/, 5, "신박/아이디어"],
  // 변신·움직임 - 영상으로 보여줄 게 확실하다
  [/접이식|폴딩|접는|접히는|펼쳐|변신|늘어나는|늘어나|확장/, 4, "접힘/변신"],
  [/회전|360|돌아가는|스윙/, 3, "회전"],
  [/압축|부피\s*감소|진공/, 4, "압축(비주얼 변화 큼)"],
  // 자동화 - "손 안 대고 된다"는 그림
  [/자동|전동|무선|충전식|센서|스마트/, 4, "자동/전동"],
  [/원터치|한\s*번에|한방에|버튼\s*하나/, 3, "원터치"],
  // 설치 마법 - 붙이는 순간이 그림이 된다
  [/자석|마그네틱|흡착|무타공|붙이는|부착/, 3, "무타공/자석"],
  // 다기능 - "이거 하나로 다 된다"
  [/만능|다용도|다목적|올인원|\d+\s*in\s*1|\d+in\d+|\d+종\s*세트/i, 3, "만능/올인원"],
  // 극단적 크기 - 상식 반전 훅이 걸린다
  [/초소형|초미니|초슬림|초경량|손바닥/, 3, "초소형"],
  [/초대형|특대|대용량|초대용량|자이언트|와이드/, 2, "초대형"],
  // 즉효성 - 결과 예고 훅이 걸린다
  [/순삭|즉시|바로\s*제거|한\s*번에\s*싹|말끔|감쪽같이/, 3, "즉효"],

  // 감점: 화면에서 변화가 없어 훅이 안 나오는 소모품류
  [/리필|본품\s*리필|묶음|낱개|1\+1|증정/, -3, "리필/묶음(변화 없음)"],
  [/세제|섬유유연제|세정제|티슈|물티슈|키친타올|비닐|봉투/, -3, "소모품(뻔함)"],
  [/커버|케이스\s*단품|파우치\s*단품|스티커/, -2, "단순 액세서리"],
];

export interface AppealResult {
  score: number;
  /** 어떤 규칙이 걸렸는지 (관리/디버깅용) */
  reasons: string[];
}

/**
 * 상품명으로 "혹하는 정도"를 계산한다.
 * 같은 그룹이 여러 번 걸려도 한 번만 센다(키워드 도배 상품이 과대평가되지 않게).
 */
export function appealDetail(productName: string): AppealResult {
  const name = productName ?? "";
  let score = 0;
  const reasons: string[] = [];
  for (const [re, weight, label] of APPEAL_RULES) {
    if (re.test(name)) {
      score += weight;
      reasons.push(`${weight > 0 ? "+" : ""}${weight} ${label}`);
    }
  }
  return { score, reasons };
}

/** 혹하는 정도 점수만 (선정 로직용) */
export function appealScore(productName: string): number {
  return appealDetail(productName).score;
}

/**
 * 검색 노출만 노리고 키워드를 도배한 "스팸성 제목" 판정.
 *
 * 이런 제목은 두 군데서 손해가 난다:
 *  1) 영상 카드에 쓸 짧은 이름이 어색하게 나온다
 *     (예: "H HNMA HN 원목 손잡이 실리콘 주방용품 세트 … 프로모션 여름 대형 할인 패션 위크 조리도구")
 *  2) 대본 생성이 상품명을 근거로 삼는데, 도배된 제목은 근거가 안 돼 훅이 뭉개진다
 *
 * 실제 등록 상품 143개 기준으로 잡은 선: 단어 수 중앙값 6개, 95% 지점이 12개다.
 * 아래 기준에 걸리는 건 143개 중 4개(2.8%)뿐이라 후보 풀에 영향이 거의 없다.
 */
const SPAM_FILLER_WORD =
  /^(프로모션|할인|특가|세일|이벤트|베스트|신상|위크|패션|인기|추천|사은품|무료배송|최저가|국내최초|1위|정품인증|초특가|핫딜)$/;
const SPAM_MAX_WORDS = 20;
const SPAM_MAX_REPEAT = 3;
const SPAM_MAX_FILLER = 3;

/** 스팸성 제목이면 사유, 아니면 null (로그/리포트에 그대로 쓴다) */
export function spamTitleReason(productName: string): string | null {
  // 옵션(쉼표/괄호 뒤)은 어차피 표시에서 잘리므로 본문만 본다
  const head = (productName ?? "").split(/[,(]/)[0].trim();
  const words = head.split(/\s+/).filter(Boolean);
  if (words.length >= SPAM_MAX_WORDS) return `제목 단어 ${words.length}개(도배)`;

  const count = new Map<string, number>();
  for (const w of words) count.set(w, (count.get(w) ?? 0) + 1);
  const [topWord, topCount] = [...count.entries()].sort((a, b) => b[1] - a[1])[0] ?? ["", 0];
  if (topCount >= SPAM_MAX_REPEAT) return `"${topWord}" ${topCount}회 반복`;

  const filler = words.filter((w) => SPAM_FILLER_WORD.test(w));
  if (filler.length >= SPAM_MAX_FILLER) return `홍보 문구 ${filler.length}개(${filler.join("/")})`;

  return null;
}

/** 스팸성 제목이면 true (스카우트 수집·영상 선정에서 제외) */
export function isSpamTitle(productName: string): boolean {
  return spamTitleReason(productName) !== null;
}

/**
 * 상품명 → 우리 카테고리 추정.
 *
 * 키워드 검색은 검색어에 카테고리가 붙어 오지만, 골드박스·카테고리 베스트셀러는
 * 상품 목록만 오므로 이름으로 판정해야 한다. 카테고리는 배경 스톡 검색어를
 * 좌우하므로(broll.ts) 확실할 때만 지정하고 애매하면 생활템으로 둔다.
 */
const CATEGORY_RULES: Array<[RegExp, string]> = [
  // 차량은 맨 앞 - "차량용 청소기"가 청소템으로 새면 집안 배경이 깔린다
  [/차량|자동차|트렁크|대시보드|와이퍼|차박/, "차량용품"],
  // 주방을 캠핑보다 앞에 둔다. 뒤에 두면 "캠핑용 접이식 도마"가 캠핑으로 잡혀
  // 배경이 야외 캠핑장이 된다(도마는 주방 장면이 맞다).
  [/주방|냄비|프라이팬|도마|식기|그릇|수저|젓가락|밀폐용기|조리|채칼|다지기|커피|텀블러|보온병/, "주방템"],
  // "랜턴"은 단독으로 두지 않는다 - "랜턴 모양 무드등"이 캠핑으로 잡히면
  // 카테고리가 야외 검색어가 되고, 그 검색어는 풍경 필터까지 꺼서(isOutdoorQuery)
  // 산·숲 클립이 정상 후보가 된다.
  [/캠핑|차박|텐트|화로대|코펠|타프|아이스박스/, "캠핑"],
  [/청소|걸레|빗자루|먼지|물때|곰팡이|배수구|세탁조|욕실|브러쉬|브러시/, "청소템"],
  [/수납|정리함|정리대|선반|칸막이|행거|옷장|서랍|후크|걸이/, "수납템"],
  [/자취|원룸|1인용|미니\s*밥솥/, "자취템"],
];

export function inferCategory(productName: string): string {
  const name = productName ?? "";
  for (const [re, category] of CATEGORY_RULES) {
    if (re.test(name)) return category;
  }
  return "생활템";
}

/**
 * 살림템 채널에 쓸 수 없는 상품인지 (골드박스·베스트셀러용).
 *
 * 키워드 검색은 우리가 검색어를 고르니 엉뚱한 게 잘 안 섞이지만, 골드박스와
 * 카테고리 베스트셀러는 쿠팡이 주는 대로 오므로 패션·식품·의약품처럼
 * "살림템 영상으로 만들 수 없는" 품목이 섞인다. 이름으로 먼저 걷어낸다.
 */
const OFF_BRAND_RULES: Array<[RegExp, string]> = [
  // "브라"는 단독으로 두지 않는다 - 브라운/브라켓/브라이트 안에서 부분일치한다
  // (한글은 \b 가 안 먹어 단어 경계를 못 준다). 실제 속옷 표기만 잡는다.
  [/티셔츠|셔츠|바지|청바지|원피스|자켓|재킷|코트|패딩|니트|양말|브래지어|브라탑|브라렛|팬티|운동화|구두|슬리퍼|백팩|지갑|목걸이|귀걸이|반지/, "패션"],
  [/즉석밥|라면|과자|음료|커피믹스|생수|우유|계란|고기|삼겹살|한우|과일|사과|귀리|쌀\b|김치|반찬|즉석|간편식|단백질\s*보충|비타민|유산균|영양제|홍삼/, "식품/건강식품"],
  [/기저귀|분유|생리대/, "소모품"],
  // "쿠션"은 메이크업 쿠션만 잡는다 - 그냥 쿠션/쿠션커버는 살림템이다
  [/립스틱|파운데이션|에어쿠션|쿠션\s*팩트|아이섀도|마스카라|스킨|로션|에센스|앰플|선크림|샴푸|린스|바디워시/, "화장품"],
  [/사료|간식\s*캔|고양이|강아지|반려/, "반려동물"],
  [/도서|소설|문제집|교재|만화책/, "도서"],
  [/상품권|기프트카드|쿠폰|이용권|여행\s*상품/, "상품권/서비스"],
];

/**
 * 살림템 신호. 위 품목 규칙보다 우선한다.
 *
 * 실측(2026-08-20): "신발 정리대"가 신발→패션, "속옷 정리함"이 속옷→패션,
 * "휴지걸이"가 휴지→소모품, "쿠션 커버"가 쿠션→화장품으로 걸러졌다.
 * 전부 우리 검색 키워드에 들어 있는 정품 살림템이라 재고를 그대로 깎고 있었다.
 * "무엇을 담는/거는/받치는 물건"이면 그 대상이 옷·휴지여도 살림템이다.
 */
const HOUSEWARE_HINT =
  /정리함|정리대|정리|수납|보관|선반|랙|행거|걸이|거치대|홀더|디스펜서|후크|바구니|커버|캡|뚜껑|받침|트레이|매트|장\b|함\b|통\b/;

/** 못 쓰는 품목이면 사유, 쓸 수 있으면 null */
export function offBrandReason(productName: string): string | null {
  const name = productName ?? "";
  // 살림템 신호가 있으면 품목 규칙을 건너뛴다 (신발"정리대", 속옷"정리함" 등)
  if (HOUSEWARE_HINT.test(name)) return null;
  for (const [re, label] of OFF_BRAND_RULES) {
    if (re.test(name)) return label;
  }
  return null;
}
