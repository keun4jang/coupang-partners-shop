/** 문자열 → 안정적 해시(시드용) */
export function nameHash(s: string): number {
  let h = 0;
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) >>> 0;
  return h;
}

/**
 * 시드로 배열에서 하나 고르기.
 * seed 가 >> 연산으로 음수(int32 오버플로)가 될 수 있어 항상 양수 인덱스로 정규화한다.
 */
export function pick<T>(arr: T[], seed: number): T {
  const i = ((Math.trunc(seed) % arr.length) + arr.length) % arr.length;
  return arr[i];
}
