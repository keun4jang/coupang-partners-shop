function byTopic(topic: string): TipTopic | null {
  return TIP_TOPICS.find((t) => t.topic === topic) ?? null;
}

/** 규칙으로 맞는 주제 전부 (위 규칙 순서대로, 중복 없이) - 네트워크 없음 */
export function matchTipTopicsByRule(productName: string): TipTopic[] {
  const out: TipTopic[] = [];
  for (const [re, topics] of RULES) {
    if (!re.test(productName)) continue;
    for (const t of topics) {
      const tt = byTopic(t);
      if (tt && !out.includes(tt)) out.push(tt);
    }
  }
  return out;
}

/** 규칙의 첫 주제 (자가 점검용) */
export function matchTipTopicByRule(productName: string): TipTopic | null {
  return matchTipTopicsByRule(productName)[0] ?? null;
}

/**
 * 상품 → 어울리는 꿀팁 주제 후보들 (첫째가 가장 잘 맞음). 없으면 빈 배열 (그 상품은 예전 상품 영상으로).
 * 규칙에 없으면 Gemini 가 목록 번호만 고른다 (새 글을 쓰지 않음).
 */
export async function matchTipTopics(productName: string, category?: string | null): Promise<{ topics: TipTopic[]; how: string }> {
  const rule = matchTipTopicsByRule(productName);
  if (rule.length) return { topics: rule, how: "낱말 규칙" };
  const list = TIP_TOPICS.map((t, i) => `${i}. ${t.topic}`).join("\n");
  const r = await geminiGenerateJson<{ indexes: number[]; reason: string }>({
    system:
      "너는 살림 쇼츠 편집자다. 상품 하나와 생활 요령 목록을 받으면, 그 요령을 따라 할 때 이 상품을 실제로 쓰는 경우의 번호만 고른다(최대 3개, 잘 맞는 순). " +
      "억지로 연결되면(예: 줄눈 제거기와 먼지 습관) 빈 배열. 확실할 때만 고른다.",
    prompt: `상품: ${productName}${category ? ` (분류: ${category})` : ""}\n\n요령 목록:\n${list}\n\n번호 목록(없으면 빈 배열)과 짧은 이유.`,
    schema: {
      type: "object",
      properties: { indexes: { type: "array", items: { type: "integer" } }, reason: { type: "string" } },
      required: ["indexes", "reason"],
    },
    temperature: 0,
  });
  const topics = [...new Set((r?.indexes ?? []).filter((i) => Number.isInteger(i) && i >= 0 && i < TIP_TOPICS.length))]
    .slice(0, 3)
    .map((i) => TIP_TOPICS[i]);
  if (!topics.length) console.log(`꿀팁 주제: 어울리는 주제 없음 (${r?.reason?.slice(0, 60) ?? "Gemini 응답 없음"})`);
  return { topics, how: topics.length ? `Gemini 선택 - ${r!.reason.slice(0, 60)}` : "없음" };
}
